"""Manifest builders. Each returns plain dicts, rendered to YAML by the advisor."""
from __future__ import annotations

from .models import GPU, Priority, WorkloadAsk

KUEUE_API = "kueue.x-k8s.io/v1beta2"   # served by Kueue >= v0.15; v1beta1 is removed upstream

PRIORITY_VALUES = {Priority.CRITICAL: 1_000_000, Priority.HIGH: 100_000,
                   Priority.NORMAL: 10_000, Priority.LOW: 100}


def priority_class(p: Priority) -> dict:
    return {
        "apiVersion": "scheduling.k8s.io/v1",
        "kind": "PriorityClass",
        "metadata": {"name": f"research-{p.value}"},
        "value": PRIORITY_VALUES[p],
        "preemptionPolicy": "Never" if p == Priority.LOW else "PreemptLowerPriority",
        "globalDefault": False,
        "description": f"{p.value} research workloads (generated by sched-advisor)",
    }


def resources(ask: WorkloadAsk) -> dict:
    req = {"cpu": f"{ask.cpu_per_pod:g}", "memory": f"{ask.memory_gib_per_pod:g}Gi"}
    lim = {"memory": f"{ask.memory_gib_per_pod:g}Gi"}  # no CPU limit: avoid CFS throttling
    if ask.gpus_per_pod:
        req[GPU] = lim[GPU] = ask.gpus_per_pod
    return {"requests": req, "limits": lim}


def pod_spec(ask: WorkloadAsk, *, node_selector: dict, tolerations: list[dict],
             scheduler_name: str | None = None, extra: dict | None = None) -> dict:
    container = {
        "name": "main",
        "image": ask.image,
        "resources": resources(ask),
    }
    if ask.command:
        container["command"] = list(ask.command)
    if ask.kind.value == "training" and ask.replicas > 1:
        container["env"] = [
            {"name": "WORLD_SIZE", "value": str(ask.replicas)},
            {"name": "MASTER_ADDR", "value": f"{ask.name}-0.{ask.name}"},
            {"name": "MASTER_PORT", "value": "29500"},
        ]
        container["ports"] = [{"containerPort": 29500, "name": "rendezvous"}]
    spec: dict = {
        "priorityClassName": f"research-{ask.priority.value}",
        "containers": [container],
    }
    if node_selector:
        spec["nodeSelector"] = node_selector
    if tolerations:
        spec["tolerations"] = tolerations
    if scheduler_name:
        spec["schedulerName"] = scheduler_name
    if ask.gpus_per_pod:
        # large shm is needed by NCCL / PyTorch dataloaders
        spec["volumes"] = [{"name": "dshm", "emptyDir": {"medium": "Memory", "sizeLimit": "64Gi"}}]
        container["volumeMounts"] = [{"name": "dshm", "mountPath": "/dev/shm"}]
    if extra:
        spec.update(extra)
    return spec


def headless_service(ask: WorkloadAsk) -> dict:
    return {
        "apiVersion": "v1", "kind": "Service",
        "metadata": {"name": ask.name, "namespace": ask.namespace},
        "spec": {"clusterIP": "None", "selector": {"job-name": ask.name},
                 "ports": [{"name": "rendezvous", "port": 29500}]},
    }


def indexed_job(ask: WorkloadAsk, spec: dict, *, labels: dict | None = None,
                annotations: dict | None = None, pod_labels: dict | None = None,
                pod_annotations: dict | None = None, suspend: bool = False) -> dict:
    spec = dict(spec, restartPolicy="Never", subdomain=ask.name)
    tmpl_meta = {"labels": {"app": ask.name, **(pod_labels or {})}}
    if pod_annotations:
        tmpl_meta["annotations"] = pod_annotations
    job = {
        "apiVersion": "batch/v1", "kind": "Job",
        "metadata": {"name": ask.name, "namespace": ask.namespace,
                     "labels": {"team": ask.team, **(labels or {})}},
        "spec": {
            "completionMode": "Indexed",
            "completions": ask.replicas,
            "parallelism": ask.replicas,
            "backoffLimitPerIndex": 0 if ask.is_gang else 2,
            "maxFailedIndexes": 0 if ask.is_gang else max(1, ask.replicas // 10),
            "podFailurePolicy": {"rules": [
                {"action": "Ignore", "onPodConditions": [{"type": "DisruptionTarget", "status": "True"}]}]},
            "template": {"metadata": tmpl_meta, "spec": spec},
        },
    }
    if annotations:
        job["metadata"]["annotations"] = annotations
    if suspend:
        job["spec"]["suspend"] = True
    if ask.kind.value == "batch":
        job["spec"].pop("podFailurePolicy")
    return job


def deployment(ask: WorkloadAsk, spec: dict, zone_label: str, hard_zone_spread: bool) -> dict:
    sel = {"app": ask.name}
    spec = dict(spec)
    spec["topologySpreadConstraints"] = [
        {"maxSkew": 1, "topologyKey": zone_label,
         "whenUnsatisfiable": "DoNotSchedule" if hard_zone_spread else "ScheduleAnyway",
         "labelSelector": {"matchLabels": sel}},
        {"maxSkew": 1, "topologyKey": "kubernetes.io/hostname",
         "whenUnsatisfiable": "ScheduleAnyway", "labelSelector": {"matchLabels": sel}},
    ]
    return {
        "apiVersion": "apps/v1", "kind": "Deployment",
        "metadata": {"name": ask.name, "namespace": ask.namespace, "labels": {"team": ask.team}},
        "spec": {"replicas": ask.replicas, "selector": {"matchLabels": sel},
                 "strategy": {"rollingUpdate": {"maxSurge": 1, "maxUnavailable": 0}},
                 "template": {"metadata": {"labels": sel}, "spec": spec}},
    }


def pdb(ask: WorkloadAsk) -> dict:
    return {"apiVersion": "policy/v1", "kind": "PodDisruptionBudget",
            "metadata": {"name": ask.name, "namespace": ask.namespace},
            "spec": {"maxUnavailable": 1, "selector": {"matchLabels": {"app": ask.name}}}}


# ---- secondary scheduler -------------------------------------------------
def scheduler_config(name: str, *, strategy: str, weights: dict[str, int],
                     coscheduling: bool = False, image_locality_weight: int | None = None) -> dict:
    profile: dict = {
        "schedulerName": name,
        "pluginConfig": [{
            "name": "NodeResourcesFit",
            "args": {"scoringStrategy": {
                "type": strategy,
                "resources": [{"name": k, "weight": v} for k, v in weights.items()]}},
        }],
    }
    plugins: dict = {}
    if image_locality_weight is not None:
        plugins["score"] = {"enabled": [{"name": "ImageLocality", "weight": image_locality_weight}]}
    if coscheduling:
        plugins["multiPoint"] = {"enabled": [{"name": "Coscheduling"}],
                                 "disabled": [{"name": "PrioritySort"}]}
        profile["pluginConfig"].append({"name": "Coscheduling", "args": {"permitWaitingTimeSeconds": 120}})
    if plugins:
        profile["plugins"] = plugins
    return {
        "apiVersion": "kubescheduler.config.k8s.io/v1",
        "kind": "KubeSchedulerConfiguration",
        "leaderElection": {"leaderElect": True, "resourceName": name, "resourceNamespace": "kube-system"},
        "profiles": [profile],
    }


def scheduler_deployment(name: str, config: dict, image: str) -> list[dict]:
    import yaml
    ns = "kube-system"
    return [
        {"apiVersion": "v1", "kind": "ServiceAccount", "metadata": {"name": name, "namespace": ns}},
        *[{"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "ClusterRoleBinding",
           "metadata": {"name": f"{name}-{role.split(':')[-1]}"},
           "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "ClusterRole", "name": role},
           "subjects": [{"kind": "ServiceAccount", "name": name, "namespace": ns}]}
          for role in ("system:kube-scheduler", "system:volume-scheduler")],
        {"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": f"{name}-config", "namespace": ns},
         "data": {"config.yaml": yaml.safe_dump(config, sort_keys=False)}},
        {"apiVersion": "apps/v1", "kind": "Deployment",
         "metadata": {"name": name, "namespace": ns, "labels": {"component": name}},
         "spec": {"replicas": 2, "selector": {"matchLabels": {"component": name}},
                  "template": {"metadata": {"labels": {"component": name}}, "spec": {
                      "serviceAccountName": name,
                      "priorityClassName": "system-cluster-critical",
                      "containers": [{"name": "scheduler", "image": image,
                                      "command": ["kube-scheduler", "--config=/etc/scheduler/config.yaml", "--v=3"],
                                      "volumeMounts": [{"name": "config", "mountPath": "/etc/scheduler"}],
                                      "resources": {"requests": {"cpu": "200m", "memory": "256Mi"}}}],
                      "volumes": [{"name": "config", "configMap": {"name": f"{name}-config"}}]}}}},
    ]


# ---- gang mechanisms -----------------------------------------------------
def pod_group(ask: WorkloadAsk) -> dict:
    return {"apiVersion": "scheduling.x-k8s.io/v1alpha1", "kind": "PodGroup",
            "metadata": {"name": ask.name, "namespace": ask.namespace},
            "spec": {"minMember": ask.replicas, "scheduleTimeoutSeconds": 600}}


def volcano_job(ask: WorkloadAsk, spec: dict) -> dict:
    spec = dict(spec, restartPolicy="Never")
    spec.pop("schedulerName", None)
    return {
        "apiVersion": "batch.volcano.sh/v1alpha1", "kind": "Job",
        "metadata": {"name": ask.name, "namespace": ask.namespace},
        "spec": {"schedulerName": "volcano", "minAvailable": ask.replicas,
                 "queue": ask.team, "priorityClassName": f"research-{ask.priority.value}",
                 "plugins": {"pytorch": ["--master=master", "--worker=worker", "--port=29500"]},
                 "policies": [{"event": "PodEvicted", "action": "RestartJob"},
                              {"event": "PodFailed", "action": "RestartJob"}],
                 "tasks": [
                     {"name": "master", "replicas": 1, "template": {"spec": spec}},
                     {"name": "worker", "replicas": ask.replicas - 1, "template": {"spec": spec}},
                 ]},
    }


def volcano_queue(ask: WorkloadAsk, gpus: int) -> dict:
    return {"apiVersion": "scheduling.volcano.sh/v1beta1", "kind": "Queue",
            "metadata": {"name": ask.team},
            "spec": {"reclaimable": True, "weight": 1,
                     "capability": {GPU: gpus}}}


def kueue_objects(ask: WorkloadAsk, *, flavor: str, node_labels: dict, gpus: int, cpus: float,
                  mem_gib: float, topology_levels: list[str] | None, tolerations: list[dict]) -> list[dict]:
    objs: list[dict] = []
    rf: dict = {"apiVersion": KUEUE_API, "kind": "ResourceFlavor",
                "metadata": {"name": flavor}, "spec": {"nodeLabels": node_labels}}
    if tolerations:
        rf["spec"]["tolerations"] = tolerations
    if topology_levels:
        objs.append({"apiVersion": KUEUE_API, "kind": "Topology",
                     "metadata": {"name": "gpu-network"},
                     "spec": {"levels": [{"nodeLabel": lvl} for lvl in topology_levels]}})
        rf["spec"]["topologyName"] = "gpu-network"
    objs.append(rf)
    objs.append({
        "apiVersion": KUEUE_API, "kind": "ClusterQueue",
        "metadata": {"name": f"{ask.team}-cq"},
        "spec": {
            "namespaceSelector": {},
            "cohortName": "research",
            "queueingStrategy": "BestEffortFIFO",
            "preemption": {"reclaimWithinCohort": "Any", "withinClusterQueue": "LowerPriority",
                           "borrowWithinCohort": {"policy": "LowerPriority"}},
            "resourceGroups": [{
                "coveredResources": ["cpu", "memory", GPU],
                "flavors": [{"name": flavor, "resources": [
                    {"name": "cpu", "nominalQuota": f"{cpus:g}"},
                    {"name": "memory", "nominalQuota": f"{mem_gib:g}Gi"},
                    {"name": GPU, "nominalQuota": gpus},
                ]}],
            }],
        },
    })
    objs.append({"apiVersion": KUEUE_API, "kind": "LocalQueue",
                 "metadata": {"name": f"{ask.team}-queue", "namespace": ask.namespace},
                 "spec": {"clusterQueue": f"{ask.team}-cq"}})
    return objs
